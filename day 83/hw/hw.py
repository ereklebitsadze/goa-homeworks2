# კლასი 1: საბანკო ანგარიში (აქ გვაქვს Encapsulation და Private/Public მეთოდები)
class BankAccount:
    def __init__(self, owner, balance):
        self.owner = owner
        # ENCAPSULATION: ბალანსს ვმალავთ ორმაგი ქვედა ტირეთით (__).
        # ეს ცვლადი გახდა private და გარედან მასზე პირდაპირ ვერავინ იმოქმედებს.
        self.__balance = balance 

    # PRIVATE METHOD: გამოიყენება მხოლოდ შიდა ტრანზაქციების ჩასაწერად
    def __log_transaction(self, message):
        print(f"[საბანკო ლოგი]: {message}")

    # PUBLIC METHOD: საჯარო მეთოდი, რომლითაც გარედან უსაფრთხოდ შემოაქვთ თანხა
    def deposit(self, amount):
        if amount > 0:
            # self-ის დახმარებით ვცვლით ზუსტად ამ ინსტანციის ბალანსს
            self.__balance += amount
            # კლასის შიგნიდან თავისუფლად ვიძახებთ private მეთოდს
            self.__log_transaction(f"{amount} ლარი დაემატა ანგარიშზე.")
        else:
            print("შეცდომა: თანხა უნდა იყოს დადებითი!")

    # PUBLIC METHOD: დამალული ბალანსის უსაფრთხოდ წასაკითხად (Getter)
    def get_balance(self):
        return f"{self.owner}-ის ანგარიშზეა: {self.__balance} ლარი"


# კლასი 2: კრიპტო საფულე (პოლიმორფიზმის საჩვენებლად)
class CryptoWallet:
    def __init__(self, owner, bitcoin_amount):
        self.owner = owner
        self.bitcoin_amount = bitcoin_amount

    # POLYMORPHISM: მეთოდს ჰქვია ზუსტად იგივე "deposit", რაც BankAccount-ში,
    # მაგრამ ეს კლასი სრულიად სხვა ლოგიკით ამუშავებს მონაცემს (თანხას აკონვერტირებს BTC-ში)
    def deposit(self, amount):
        converted_btc = amount / 150000  # დავუშვათ 1 BTC = 150,000 ლარს
        self.bitcoin_amount += converted_btc
        print(f"[კრიპტო ლოგი]: საფულე შეივსო {amount} ლარის ექვივალენტი ბიტკოინით.")

    # POLYMORPHISM: იგივე სახელის მქონე მეთოდი, რომელიც სხვანაირ პასუხს აბრუნებს
    def get_balance(self):
        return f"{self.owner}-ის საფულეშია: {self.bitcoin_amount} BTC"


# --- INSTANCES (ობიექტების შექმნა და ტესტირება) ---

# ვქმნით ორ კონკრეტულ ობიექტს (Instance-ს) შესაბამისი კლასებიდან
